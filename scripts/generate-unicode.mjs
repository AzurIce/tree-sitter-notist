// Unicode predicates used by the reference Rust lexer: alphabetic/alphanumeric.
import { writeFileSync } from 'node:fs';
const ranges = predicate => {
  const result = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (!predicate.test(String.fromCodePoint(cp))) continue;
    const start = cp;
    while (cp < 0x10ffff && predicate.test(String.fromCodePoint(cp + 1))) cp++;
    result.push(`  {0x${start.toString(16)}, 0x${cp.toString(16)}}`);
  }
  return result.join(',\n');
};
writeFileSync(new URL('../src/unicode.h', import.meta.url), `// Generated by scripts/generate-unicode.mjs with Unicode ${process.versions.unicode}.\n#ifndef NOTIST_UNICODE_H\n#define NOTIST_UNICODE_H\n#include <stdint.h>\nstatic const uint32_t alphabetic_ranges[][2] = {\n${ranges(/\p{Alphabetic}/u)}\n};\nstatic const uint32_t number_ranges[][2] = {\n${ranges(/\p{Number}/u)}\n};\nstatic bool in_ranges(int32_t c, const uint32_t ranges[][2], unsigned count) {\n  unsigned low = 0, high = count;\n  while (low < high) {\n    unsigned mid = low + (high - low) / 2;\n    if ((uint32_t)c < ranges[mid][0]) high = mid;\n    else if ((uint32_t)c > ranges[mid][1]) low = mid + 1;\n    else return true;\n  }\n  return false;\n}\n#define IN_RANGES(c, ranges) in_ranges(c, ranges, sizeof(ranges) / sizeof(ranges[0]))\n#endif\n`);
