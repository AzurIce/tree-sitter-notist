/** Notist's current markup and literal grammar. No whitespace is implicit:
 * call paths, argument keys, negative numbers, and body slots are adjacent. */
/// <reference types="tree-sitter-cli/dsl" />
module.exports = grammar({
  name: 'notist',
  extras: $ => [$.comment],
  externals: $ => [
    $._newline, $.identifier, $.fn_keyword, $.string, $.boolean, $.text,
    $.heading_marker, $.list_marker, $.divider,
    $._strong_open, $._strong_close, $._emphasis_open, $._emphasis_close,
    $._strike_open, $._strike_close,
    $._call_start, $._body_open, $._body_close,
    $._wiki_open, $.link_target, $._wiki_pipe, $._wiki_close,
    $._link_open, $._embed_start, $._link_label_close, $.link_destination,
    $.raw_inline, $.raw_fence_start, $.raw_content, $.raw_fence_end, $.math,
    $.comment, $._table_start, $.table_row, $.table_delimiter,
    $._annotation_start, $._module_annotation_start,
    $._import_start, $._path_dot, $._arguments_open, $._comptime_open,
    $._comptime_close, $._or_operator, $._and_operator, $._equality_operator,
    $._compare_operator, $._sum_operator, $._product_operator,
  ],
  conflicts: $ => [[$.dict], [$.array], [$.arguments], [$.parameters], [$.comptime_parameters], [$.type], [$.parameter], [$.table], ...require('./common/code-conflicts')($)],
  rules: {
    source_file: $ => repeat($._markup_item),
    ...require('./common/notist'),
    ...require('./common/code'),
    _markup_item: $ => choice($._inline_item, $._newline, $.heading,
      $.list_marker, $.divider, $.raw_block, $.table),
    _inline_item: $ => choice($.text, $.comment, $.escape, $.explicit_break,
      $.strong, $.emphasis, $.strike, $.raw_inline, $.math,
      $.link, $.embed, $.wikilink, $.call, $.reference, $.import_declaration, $.annotation),
    heading: $ => prec.right(seq($.heading_marker, optional(field('title', $.title)))),
    title: $ => prec.right(repeat1($._inline_item)),
    strong: $ => seq(alias($._strong_open, '*'), repeat1(choice($._inline_item, $._newline)), alias($._strong_close, '*')),
    emphasis: $ => seq(alias($._emphasis_open, '_'), repeat1(choice($._inline_item, $._newline)), alias($._emphasis_close, '_')),
    strike: $ => seq(alias($._strike_open, '~'), repeat1(choice($._inline_item, $._newline)), alias($._strike_close, '~')),
    escape: _ => /\\[=*_~\\\[\]()|#$@!+`-]/,
    explicit_break: _ => /\\(?:\r\n|\r|\n)/,
    wikilink: $ => seq(alias($._wiki_open, '[['), optional(field('target', $.link_target)),
      optional(seq(alias($._wiki_pipe, '|'), repeat($._inline_item))), alias($._wiki_close, ']]')),
    link: $ => seq(alias($._link_open, '['), repeat($._inline_item), alias($._link_label_close, ']'),
      field('destination', $.link_destination)),
    embed: $ => seq(alias($._embed_start, '!'), alias($._link_open, '['), repeat($._inline_item), alias($._link_label_close, ']'),
      field('destination', $.link_destination)),
    raw_block: $ => seq($.raw_fence_start, optional($.raw_content), $.raw_fence_end),
    table: $ => seq(field('header', $.table_header), $._newline,
      $.table_delimiter, repeat(seq($._newline, $.table_row))),
    table_header: $ => seq($._table_start, optional($.table_row)),
    module: $ => repeat1(choice($._trivia, $.function_declaration, $.code_import)),
    code_import: $ => seq('import', repeat($._trivia), field('source', $.string), repeat($._trivia),
      optional(seq('as', repeat($._trivia), field('alias', $.identifier), repeat($._trivia))), ';'),
    function_declaration: $ => seq($.fn_keyword, repeat($._trivia),
      field('name', $.identifier), repeat($._trivia), optional(seq(field('comptime', $.comptime_parameters), repeat($._trivia))), optional(seq(field('parameters', $.parameters), repeat($._trivia))),
      optional(seq(field('children', $.children_declaration),
        repeat($._trivia))), '->', repeat($._trivia), field('return_type', $.type),
      repeat($._trivia), choice(';', field('body', $.block_expression))),
    comptime_parameters: $ => seq('<', repeat($._trivia), optional(seq($.parameter,
      repeat(seq(repeat($._trivia), ',', repeat($._trivia), $.parameter)),
      repeat($._trivia), optional(','), repeat($._trivia))), '>'),
    parameters: $ => seq('(', repeat($._trivia), optional(seq($.parameter,
      repeat(seq(repeat($._trivia), ',', repeat($._trivia), $.parameter)),
      repeat($._trivia), optional(','), repeat($._trivia))), ')'),
    parameter: $ => seq(field('name', $.identifier), repeat($._trivia), choice(
      seq('?', repeat($._trivia), ':', repeat($._trivia), field('type', $.type)),
      seq(':', repeat($._trivia), field('type', $.type),
        optional(seq(repeat($._trivia), $.default_value))))),
    default_value: $ => seq('=', repeat($._trivia), field('value', $._value)),
    children_declaration: $ => seq('[', repeat($._trivia), 'children',
      repeat($._trivia), ':', repeat($._trivia), field('type', $.type),
      repeat($._trivia), ']'),
    type: $ => seq(field('name', $.path), optional(seq(repeat($._trivia), '<',
      repeat($._trivia), $.type, repeat(seq(repeat($._trivia), ',',
        repeat($._trivia), $.type)), repeat($._trivia), optional(','),
      repeat($._trivia), '>'))),
  },
});
